def test_slicer_writes_project_and_command(tmp_path, monkeypatch):
    install = tmp_path / "cp"
    fake = slicer.executable(install)               # Linux bin/CrealityPrint, Windows CrealityPrint.exe
    fake.parent.mkdir(parents=True, exist_ok=True)
    fake.write_text("")
    monkeypatch.setattr(slicer, "missing_libraries", lambda install=None: [])
    machine = profiles.Profile("machine", "M", {"name": "M", "nozzle_diameter": ["0.4"]})
    process = profiles.Profile("process", "P", {"name": "P", "inherits": "x"}, {"wall_loops": "3"})
    filament = profiles.Profile("filament", "F", {"name": "F", "nozzle_temperature": ["220"], "filament_id": "01"})
    triangles = box_mesh() + np.array([50.0, 60.0, 5.0])
    job = slicer.prepare(tmp_path / "job", [("A", triangles, 1), ("B", triangles + 100, 2)], machine, process,
                         [filament, filament], install)
    assert job.arguments[1] == "--cli" and job.arguments[-1] == str(job.project)
    import zipfile
    with zipfile.ZipFile(job.project) as archive:
        settings = json.loads(archive.read("Metadata/project_settings.config"))
        model = archive.read("3D/3dmodel.model").decode()
        config = archive.read("Metadata/model_settings.config").decode()
    # Prozessänderung übernommen, Filamentwerte je Fach als Liste, filament_id als Einzelwert, Farben je Fach
    assert settings["wall_loops"] == "3" and settings["nozzle_temperature"] == ["220", "220"]
    assert settings["filament_id"] == "01" and len(settings["filament_colour"]) == 2
    assert settings["printer_settings_id"] == "M" and settings["filament_settings_id"] == ["F", "F"]
    assert "BambuStudio" in model and 'key="extruder" value="2"' in config
    assert model.count("<object ") == 2


class _FakeMoonraker(BaseHTTPRequestHandler):
    uploads: list = []
    state, printing = "printing", "x.gcode"       # Zustand und Druckdatei, die der Testdrucker meldet

    def log_message(self, *args):
        pass

    def _send(self, data):
        body = json.dumps({"result": data}).encode()
        self.send_response(200)
        self.send_header("Content-Length", str(len(body)))
        self.end_headers()
        self.wfile.write(body)

    def do_GET(self):
        if self.path.startswith("/printer/info"):
            self._send({"state": "ready", "hostname": "K2Plus-Test"})
        else:
            self._send({"status": {"print_stats": {"state": _FakeMoonraker.state, "filename": _FakeMoonraker.printing},
                                   "display_status": {"progress": 0.5},
                                   "extruder": {"temperature": 219.5, "target": 220},
                                   "heater_bed": {"temperature": 60, "target": 60}}})

    def do_POST(self):
        length = int(self.headers.get("Content-Length", 0))
        body = self.rfile.read(length)
        _FakeMoonraker.uploads.append((self.path, body))
        if self.path.startswith("/server/files/upload"):
            # Moonraker: die Datei, die gerade gedruckt wird, darf nicht überschrieben werden (403)
            if _FakeMoonraker.state == "printing" and f'filename="{_FakeMoonraker.printing}"'.encode() in body:
                answer = json.dumps({"error": {"code": 403, "message": "Forbidden", "traceback": "…"}}).encode()
                self.send_response(403)
                self.send_header("Content-Length", str(len(answer)))
                self.end_headers()
                self.wfile.write(answer)
                return
            name = body.split(b'filename="', 1)[1].split(b'"', 1)[0].decode()
            self._send({"item": {"path": name}})
            return
        self._send({})


def test_moonraker_status_and_upload(tmp_path):
    server = HTTPServer(("127.0.0.1", 0), _FakeMoonraker)
    threading.Thread(target=server.serve_forever, daemon=True).start()
    try:
        printer = moonraker.Moonraker("127.0.0.1", server.server_address[1])
        assert printer.info()["state"] == "ready"
        status = printer.status()
        assert status.state == "printing" and status.progress == 0.5
        assert status.temperatures["Düse"] == (219.5, 220.0)
        path = tmp_path / "wolfcad.gcode"
        path.write_text("G1 X1\n")
        # Runde 79: während eines Drucks lässt sich nichts starten – klare Meldung statt der rohen 403-Antwort
        _FakeMoonraker.state, _FakeMoonraker.printing = "printing", "wolfcad.gcode"
        with pytest.raises(moonraker.PrinterError, match="druckt gerade „wolfcad.gcode“"):
            printer.upload(path, start=True)
        # „Nur hochladen“ mit dem Namen der laufenden Druckdatei: bekommt einen freien Namen
        assert printer.upload(path, start=False) == "wolfcad (2).gcode"
        # ohne laufenden Druck: hochladen und starten unter dem eigenen Namen
        _FakeMoonraker.state = "standby"
        assert printer.upload(path, start=True) == "wolfcad.gcode"
        upload_path, body = _FakeMoonraker.uploads[-1]
        assert upload_path == "/server/files/upload" and b'name="print"\r\n\r\ntrue' in body and b"G1 X1" in body
        # Runde 83: Fortschritt beim Hochladen – mehrere Meldungen, die letzte ist „alles gesendet“
        big = tmp_path / "gross.gcode"
        big.write_text("G1 X1 Y1\n" * 20000)
        reports = []
        assert printer.upload(big, start=False, progress=lambda sent, total: reports.append((sent, total)))
        assert len(reports) > 3 and reports[-1][0] == reports[-1][1] and reports[-1][1] > big.stat().st_size
        assert all(a[0] <= b[0] for a, b in zip(reports, reports[1:]))
        assert b"G1 X1 Y1" in _FakeMoonraker.uploads[-1][1]
    finally:
        _FakeMoonraker.state, _FakeMoonraker.printing = "printing", "x.gcode"
        server.shutdown()


def test_printer_errors_are_readable():
    # Moonraker schickt bei 403 eine JSON-Antwort mit Traceback – angezeigt wird ein verständlicher Satz
    text = moonraker._explain(403, json.dumps({"error": {"code": 403, "message": "Forbidden", "traceback": "x"}}))
