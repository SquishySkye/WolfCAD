@pytest.mark.skipif(not profiles.Library().available or slicer.missing_libraries(),
                    reason="Creality Print fehlt oder seine Systembibliotheken fehlen")
def test_real_slice_keeps_positions_and_filaments(tmp_path):
    """Echter Slicer: zwei Würfel an festen Stellen mit zwei Filamenten – Lage bleibt, G-Code hat beide Fächer."""
    import subprocess
    library = profiles.Library()
    printer = "Creality K2 Plus 0.4 nozzle"
    bed = plate.Plate(350, 350, 350)
    first, second = bed.add("A", box_mesh(20, 20, 10)), bed.add("B", box_mesh(20, 20, 10))
    first.x, first.y, second.x, second.y = 50, 60, 290, 280
    pla = library.profile("filament", library.default_filament(printer))
    petg = library.profile("filament", "CR-PETG @Creality K2 Plus 0.4 nozzle")
    job = slicer.prepare(tmp_path, [("A", first.placed(), 1), ("B", second.placed(), 2)],
                         library.profile("machine", printer),
                         library.profile("process", library.default_process(printer)), [pla, petg])
    done = subprocess.run(job.arguments, env=slicer.cli_environment(), capture_output=True, timeout=300)
    assert done.returncode == 0, job.result()
    text = job.gcode.read_text(errors="replace")
    assert "CENTER=50,60" in text and "CENTER=290,280" in text
    assert "\nT1" in text or "M8200 P S1" in text
    path = gcode.read(job.gcode)
    assert path.layer_count == 50 and "Druckzeit" in path.info


def test_mirror_cut_split_and_paint():
    bed = plate.Plate(200, 200, 200)
    item = bed.add("Q", box_mesh(20, 10, 10))
    volume = abs(meshes._signed_volume(*meshes._indexed(item.placed())))
    item.mirror("X")
    # gespiegelt bleibt das Netz richtig herum (positives Volumen) und gleich groß
    assert meshes._signed_volume(*meshes._indexed(item.placed())) == pytest.approx(volume)
    lower, upper = bed.cut(item, 4.0)
    assert lower.size()[2] == pytest.approx(4, abs=1e-3) and upper.size()[2] == pytest.approx(6, abs=1e-3)
    two = np.concatenate([box_mesh(10, 10, 10), box_mesh(10, 10, 10) + np.array([30.0, 0, 0])])
    joined = bed.add("Zwei", two)
    assert len(bed.split_parts(joined)) == 2
    painter = bed.objects[0]
    painter.subdivide(2.0)
    assert np.linalg.norm(painter.mesh[:, 1] - painter.mesh[:, 0], axis=1).max() <= 2.0 + 1e-9
    centre = painter.placed().reshape(-1, 3).mean(0)
    assert painter.paint("color", centre, 3.0, 2) > 0 and painter.color_paint.max() == 2


