def test_gcode_reader(tmp_path):
    path = tmp_path / "t.gcode"
    path.write_text(GCODE)
    result = gcode.read(path)
    assert result.layer_count == 2 and result.layer_heights == pytest.approx([0.2, 0.4])
    assert len(result.layers["Sparse infill"]) == 1
    walls = result.layers["Outer wall"]
    assert (walls == 0).sum() == 2 and (walls == 1).sum() > 2          # Bogen als Sehnenzug
    assert result.info["Druckzeit"] == "1m 2s" and result.info["Filament (g)"] == "0.12"
    assert len(result.travel) >= 1


