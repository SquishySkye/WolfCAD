def box_mesh(length=20.0, width=10.0, height=5.0) -> np.ndarray:
    state = ft.BuildState()
    solids.Box(length=length, width=width, height=height).apply(state)
    return meshes.tessellate(next(iter(state.bodies.values())))


def test_plate_add_rotate_and_lay_flat():
    bed = plate.Plate(350, 350, 350)
    item = bed.add("Quader", box_mesh() + np.array([100.0, 50.0, 30.0]))   # Lage im Entwurf spielt keine Rolle
    low, high = item.bounds()
    assert low[2] == pytest.approx(0) and (low[:2] + high[:2]) / 2 == pytest.approx([175, 175])
    assert item.size() == pytest.approx([20, 10, 5])
    item.rotate("Y", 90)                                    # steht jetzt hochkant, liegt aber auf dem Bett
    assert item.size() == pytest.approx([5, 10, 20]) and item.bounds()[0][2] == pytest.approx(0)
    # die größte ebene Fläche nach unten legen: wieder flach
    normal, area = item.flat_faces()[0]
    assert area == pytest.approx(200)
    item.lay_on(normal)
    assert item.size()[2] == pytest.approx(5)


def test_plate_arrange_and_duplicate():
    bed = plate.Plate(100, 100, 100)
    item = bed.add("A", box_mesh(30, 30, 5))
    bed.duplicate(item, 3)
    assert len(bed.objects) == 4 and len({o.name for o in bed.objects}) == 4
    assert bed.arrange() and not bed.problems()
    # keine Überschneidung zwischen den Objekten
    boxes = [o.bounds() for o in bed.objects]
    for i, (a_low, a_high) in enumerate(boxes):
        for b_low, b_high in boxes[i + 1:]:
            assert a_high[0] <= b_low[0] + 1e-6 or b_high[0] <= a_low[0] + 1e-6 \
                or a_high[1] <= b_low[1] + 1e-6 or b_high[1] <= a_low[1] + 1e-6
    bed.duplicate(item, 10)
    assert not bed.arrange() and bed.problems()             # passt nicht mehr: klarer Hinweis


