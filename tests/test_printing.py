def test_calibration_post_processing():
    from wolfcad.printing import calibration
    text = "G1 X1\n;LAYER_CHANGE\n;Z:0.2\nG1 E-.8 F2400\n;LAYER_CHANGE\n;Z:25\nG1 E-.8 F2400\nG1 E16 F500\n"
    tower = calibration.temperature_tower(start=240, end=230, step=5)
    temps = tower.post(text)
    assert "M104 S240" in temps and "M104 S230" in temps
    advance = calibration.pressure_advance_tower(start=0.0, end=0.1, height=50)
    assert "SET_PRESSURE_ADVANCE ADVANCE=0.0500" in advance.post(text)
    retraction = calibration.retraction_tower(start=0.0, end=2.0, height=40).post(text)
    assert "G1 E-1.250 F2400" in retraction and "G1 E16 F500" in retraction     # Spülmenge bleibt
    assert len(calibration.flow_blocks().objects) == 6


@pytest.mark.skipif(not profiles.Library().available or slicer.missing_libraries(),
                    reason="Creality Print fehlt oder seine Systembibliotheken fehlen")
def test_real_slice_with_painted_supports(tmp_path):
    """Gemalte Stützen unter einer auskragenden Platte: nur mit Bemalung entstehen Stützen (Modus „manuell“)."""
    import subprocess
    state = ft.BuildState()
    solids.Box(length=10, width=10, height=20).apply(state)
    solids.Box(center_x=12, length=34, width=10, height=4, offset=20, operation="Vereinigen").apply(state)
    bed = plate.Plate(350, 350, 350)
    item = bed.add("T", meshes.tessellate(next(iter(state.bodies.values()))))
    item.subdivide(3.0)
    placed = item.placed()
    normals = np.cross(placed[:, 1] - placed[:, 0], placed[:, 2] - placed[:, 0])
    paint = np.where((normals[:, 2] < -0.5) & (placed.mean(1)[:, 2] > 10), 1, 0).astype(np.int8)
    library = profiles.Library()
    printer = "Creality K2 Plus 0.4 nozzle"
    process = library.profile("process", library.default_process(printer))
    process.changes = {"enable_support": "1", "support_type": "normal(manual)"}
    counts = []
    for extra in ({}, {"supports": paint}):
        job = slicer.prepare(tmp_path / str(len(counts)), [("T", placed, 1, extra)],
                             library.profile("machine", printer), process,
                             [library.profile("filament", library.default_filament(printer))])
        subprocess.run(job.arguments, env=slicer.cli_environment(), capture_output=True, timeout=300, check=True)
        counts.append(len(gcode.read(job.gcode).segments.get("Support", [])))
    assert counts[0] == 0 and counts[1] > 100
